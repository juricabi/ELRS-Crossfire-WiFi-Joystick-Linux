#!/bin/sh
# Build elrs-wifi-joystick and its unit tests.
#
#   ./build.sh [target] [what] [test names...]
#     target: native (default: this machine, cc), or a static Linux binary made with zig cc:
#             x86_64, i686, aarch64, armv7, armv6, riscv64; "all" = every static target
#     what:   all (default: the program + tests), prog, tests, test (build both, then run the unit tests;
#             names limit which), clean
#
# Environment:
#   CC       compiler for native (default cc); the static targets always use "zig cc"
#   OPT      optimization flags (default -O2)
#   WERROR   1: warnings are errors (CI)
#   SAN      1: native build with AddressSanitizer + UBSan (tests)
#   VERSION  the version compiled in (default: the VERSION file)
#   RUN      prefix for running cross-built tests (e.g. qemu-aarch64-static); "" = run directly
#   BUILD    output directory (default build): build/<target>/elrs-wifi-joystick, build/<target>/test_*
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
cd "$HERE"
TARGET=${1:-native}
WHAT=${2:-all}
# shellcheck disable=SC2015  # shift 2 cannot fail with 2 arguments
[ $# -ge 2 ] && shift 2 || shift $#
ONLY="$*"
OPT=${OPT:--O2}
if [ -z "$VERSION" ]; then
  if [ -f VERSION ]; then VERSION=$(tr -d ' \r\n' < VERSION); else VERSION=0.0.0-dev; fi
fi

if [ "$TARGET" = all ]; then
  # shellcheck disable=SC2086  # ONLY: test names, one word each
  for t in x86_64 i686 aarch64 armv7 armv6 riscv64; do "$0" "$t" "$WHAT" $ONLY; done
  exit 0
fi

TFLAGS=""
case "$TARGET" in
  native)  CC=${CC:-cc} ;;
  x86_64)  CC="zig cc"; TFLAGS="-target x86_64-linux-musl" ;;
  i686)    CC="zig cc"; TFLAGS="-target x86-linux-musl -mcpu=i686" ;;
  aarch64) CC="zig cc"; TFLAGS="-target aarch64-linux-musl" ;;
  # ARMv7-A with VFPv3-D16 and no NEON (the armhf baseline): Pi 2/3/4 with a 32-bit OS and every 32-bit
  # ARMv7 board (cortex_a7 would emit NEON/VFPv4 and die with SIGILL on Cortex-A8/A9 boards)
  armv7)   CC="zig cc"; TFLAGS="-target arm-linux-musleabihf -mcpu=generic+v7a+vfp3d16-neon-d32" ;;
  armv6)   CC="zig cc"; TFLAGS="-target arm-linux-musleabihf -mcpu=arm1176jzf_s" ;;  # Pi 1 / Zero (W)
  riscv64) CC="zig cc"; TFLAGS="-target riscv64-linux-musl" ;;
  *) echo "unknown target $TARGET (native x86_64 i686 aarch64 armv7 armv6 riscv64 all)" >&2; exit 2 ;;
esac
DBG=""
LDSTATIC=""
if [ "$TARGET" = native ]; then
  DBG="-g"
  if [ "$SAN" = 1 ]; then DBG="-g -fsanitize=address,undefined -fno-omit-frame-pointer"; fi
else
  LDSTATIC="-static -s"
fi

OUT="${BUILD:-build}/$TARGET"
mkdir -p "$OUT/obj/core" "$OUT/obj/src" "$OUT/obj/tests" "$OUT/gen"
if [ "$WHAT" = clean ]; then rm -rf "$OUT"; echo "removed $OUT"; exit 0; fi

WARN="-Wall -Wextra -Wno-unused-parameter"
[ "$WERROR" = 1 ] && WARN="$WARN -Werror"
# shellcheck disable=SC2089  # the quotes are for the compiler: APP_VERSION is a C string
CFLAGS="$TFLAGS $OPT $DBG -std=gnu99 -D_GNU_SOURCE -Icore -Isrc -I$OUT/gen -DAPP_VERSION=\"$VERSION\""
LIBS="-lpthread -lm"

# the web page, embedded: web/index.html -> $OUT/gen/webpage.h (a placeholder until the page exists)
GEN="$OUT/gen/webpage.h"
if [ ! -f "$GEN" ] || { [ -f web/index.html ] && [ web/index.html -nt "$GEN" ]; } || [ "$0" -nt "$GEN" ]; then
  {
    echo "/* generated by build.sh from web/index.html - do not edit */"
    echo "static const unsigned char WEBPAGE[] = {"
    if [ -f web/index.html ]; then
      od -An -v -tx1 web/index.html | sed 's/[0-9a-f][0-9a-f]/0x&,/g'
    else
      printf '<!doctype html><title>elrs-wifi-joystick</title><p>web/index.html is missing in this build.' | od -An -v -tx1 | sed 's/[0-9a-f][0-9a-f]/0x&,/g'
    fi
    echo "};"
    echo "#define WEBPAGE_LEN (sizeof WEBPAGE)"
  } > "$GEN.tmp"
  mv "$GEN.tmp" "$GEN"
fi

# objects of other flags (SAN, OPT, WERROR, VERSION) must not be reused: start over when they change
STAMP="$OUT/obj/flags"
if [ "$(cat "$STAMP" 2>/dev/null)" != "$CC $CFLAGS $WARN" ]; then
  rm -f "$OUT"/obj/core/*.o "$OUT"/obj/src/*.o "$OUT"/obj/tests/*.o
  printf '%s\n' "$CC $CFLAGS $WARN" > "$STAMP"
fi
# shellcheck disable=SC2012  # plain file names
NEWEST_H=$(ls -t core/*.h src/*.h "$GEN" 2>/dev/null | head -1)
compile() {  # src obj
  if [ ! -f "$2" ] || [ "$1" -nt "$2" ] || [ "$NEWEST_H" -nt "$2" ]; then
    echo "  CC $1"
    # shellcheck disable=SC2086,SC2090
    $CC $CFLAGS $WARN -c "$1" -o "$2"
  fi
}

LIB_OBJ=""
for f in core/*.c; do
  [ -f "$f" ] || continue
  o="$OUT/obj/core/$(basename "$f" .c).o"; compile "$f" "$o"; LIB_OBJ="$LIB_OBJ $o"
done
for f in src/*.c; do
  [ -f "$f" ] || continue
  n=$(basename "$f" .c)
  o="$OUT/obj/src/$n.o"; compile "$f" "$o"
  [ "$n" = main ] || LIB_OBJ="$LIB_OBJ $o"
done

if [ "$WHAT" = all ] || [ "$WHAT" = prog ] || [ "$WHAT" = test ]; then
  if [ -f src/main.c ]; then
    echo "  LD elrs-wifi-joystick"
    # shellcheck disable=SC2086,SC2090
    $CC $CFLAGS $LDSTATIC -o "$OUT/elrs-wifi-joystick" "$OUT/obj/src/main.o" $LIB_OBJ $LIBS
  fi
fi

TESTS=""
for t in core/tests/test_*.c tests/test_*.c; do
  [ -f "$t" ] || continue
  n=$(basename "$t" .c)
  if [ -n "$ONLY" ]; then case " $ONLY " in *" $n "*) ;; *) continue ;; esac; fi
  TESTS="$TESTS $t"
done

if [ "$WHAT" = all ] || [ "$WHAT" = tests ] || [ "$WHAT" = test ]; then
  for t in $TESTS; do
    n=$(basename "$t" .c)
    compile "$t" "$OUT/obj/tests/$n.o"
    echo "  LD $n"
    # tests may define what they need instead of a module (stubs): those objects are left out
    STUBBED=$(sed -n 's|^/\* *STUBS: *\(.*\)\*/.*|\1|p' "$t" | head -1)
    OBJS=""
    for o in $LIB_OBJ; do
      skip=0
      for s in $STUBBED; do [ "$(basename "$o" .o)" = "$s" ] && skip=1; done
      [ $skip = 1 ] || OBJS="$OBJS $o"
    done
    # shellcheck disable=SC2086,SC2090
    $CC $CFLAGS $LDSTATIC -o "$OUT/$n" "$OUT/obj/tests/$n.o" $OBJS $LIBS
  done
fi

if [ "$WHAT" = test ]; then
  fail=0
  for t in $TESTS; do
    n=$(basename "$t" .c)
    if $RUN "$OUT/$n"; then echo "PASS $n"; else echo "FAIL $n"; fail=1; fi
  done
  exit $fail
fi
echo "built in $OUT"
